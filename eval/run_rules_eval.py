#!/usr/bin/env python3
"""How well do the scam-script rules separate scam calls from ordinary ones?

    python eval/run_rules_eval.py        # from the repo root; prints the summary, writes eval/results.md

Each call in eval/transcripts.jsonl is run through the rules exactly as a live
call is (app/feature/scam_rules.py, with the session's duplicate check and its
3-flags-per-category cap), and its script score is compared with two lines:
  ALERT  80  the live "this call matches a known scam script" alert
  SIGNS  40  "some scam signs": medium risk on its own
The script score is only one of Veracity's three signals (number, voice,
script); this measures the script layer alone, on text, without Whisper's errors.
"""

import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "veracity-backend"))

from app.feature import scam_rules  # noqa: E402

ALERT, SIGNS = 80, 40
DATA = ROOT / "eval" / "transcripts.jsonl"
OUT = ROOT / "eval" / "results.md"


def score_call(lines: list[str]) -> tuple[int, list[dict]]:
    flags: list[dict] = []
    for line in lines:
        for hit in scam_rules.scan(line):
            if scam_rules.is_duplicate(hit["evidence"], flags):
                continue
            if sum(f["category"] == hit["category"] for f in flags) >= 3:
                continue
            flags.append(hit)
    return scam_rules.script_score({f["category"] for f in flags}), flags


def rates(rows: list[dict], threshold: int) -> dict:
    tp = sum(r["label"] == "scam" and r["score"] >= threshold for r in rows)
    fn = sum(r["label"] == "scam" and r["score"] < threshold for r in rows)
    fp = sum(r["label"] == "benign" and r["score"] >= threshold for r in rows)
    tn = sum(r["label"] == "benign" and r["score"] < threshold for r in rows)
    return {
        "tp": tp, "fn": fn, "fp": fp, "tn": tn,
        "recall": tp / (tp + fn) if tp + fn else 0.0,
        "precision": tp / (tp + fp) if tp + fp else 0.0,
        "false_alarm": fp / (fp + tn) if fp + tn else 0.0,
    }


def main() -> None:
    rows = []
    for raw in DATA.read_text(encoding="utf-8").splitlines():
        call = json.loads(raw)
        score, flags = score_call(call["lines"])
        rows.append({**call, "score": score, "categories": sorted({f["category"] for f in flags})})

    counts = Counter((r["language"], r["label"]) for r in rows)
    languages = sorted({r["language"] for r in rows})
    at = {name: rates(rows, t) for name, t in (("alert", ALERT), ("signs", SIGNS))}

    md = [
        "# Scam-script rules: evaluation",
        "",
        f"Generated by `python eval/run_rules_eval.py` on `eval/transcripts.jsonl`: {len(rows)} calls, "
        f"{sum(r['label'] == 'scam' for r in rows)} scam and {sum(r['label'] == 'benign' for r in rows)} ordinary.",
        "",
        "**What this is:** short call transcripts written for this test (with AI assistance), modelled on scam "
        "patterns that the FTC, the FBI and Indian police describe, and on ordinary calls that share their words "
        "(a real bank's fraud check, a delivery driver, a friend asking for $20). **What it isn't:** recordings "
        "of real calls. It tests the rules on clean text; on a live call Whisper's mistakes come first.",
        "",
        "| Language | Scam calls | Ordinary calls |",
        "| --- | ---: | ---: |",
        *[f"| {lang} | {counts[(lang, 'scam')]} | {counts[(lang, 'benign')]} |" for lang in languages],
        "",
        "## Results",
        "",
        "| Threshold | Scam calls caught (recall) | Ordinary calls flagged (false alarms) | Precision |",
        "| --- | ---: | ---: | ---: |",
    ]
    for name, threshold, label in (
        ("alert", ALERT, "Live alert, script ≥ 80"),
        ("signs", SIGNS, "Some scam signs, ≥ 40: Protected Send holds for a callback"),
    ):
        r = at[name]
        md.append(
            f"| {label} | {r['tp']}/{r['tp'] + r['fn']} ({r['recall']:.0%}) | {r['fp']}/{r['fp'] + r['tn']} "
            f"({r['false_alarm']:.0%}) | {r['precision']:.0%} |"
        )

    md += [
        "",
        "**Reading it:** the live alert is deliberately strict, so most scams in this set land between 40 and 79 "
        "(“some scam signs”) rather than setting off the red banner. That is why the payment gate doesn't wait "
        "for the alert: any payment made on a call scoring 40 or more is held until the user calls the person "
        "back on a saved number (`gate_level` in `app/feature/payment_gate.py`).",
        "",
        "Recall at the live alert, by language:",
        "",
        "| Language | Caught |",
        "| --- | ---: |",
    ]
    by_lang = defaultdict(list)
    for r in rows:
        if r["label"] == "scam":
            by_lang[r["language"]].append(r["score"] >= ALERT)
    for lang in languages:
        if by_lang[lang]:
            md.append(f"| {lang} | {sum(by_lang[lang])}/{len(by_lang[lang])} |")

    missed = [r for r in rows if r["label"] == "scam" and r["score"] < ALERT]
    alarms = [r for r in rows if r["label"] == "benign" and r["score"] >= SIGNS]
    flagged = [r for r in rows if r["label"] == "benign" and 0 < r["score"] < SIGNS]
    md += ["", "## Scam calls below the alert", "", "| Call | Script score | Categories found |", "| --- | ---: | --- |"]
    md += [f"| `{r['id']}` | {r['score']} | {', '.join(r['categories']) or 'none'} |" for r in missed] or ["| none | | |"]
    md += ["", "## Ordinary calls at or above 40", "", "| Call | Script score | Categories found |", "| --- | ---: | --- |"]
    md += [f"| `{r['id']}` | {r['score']} | {', '.join(r['categories'])} |" for r in alarms] or ["| none | | |"]
    md += [
        "",
        f"{len(flagged)} more ordinary calls picked up a flag or two but stayed under 40 (low risk), for example "
        "a delivery driver's “parcel” or a real bank saying it will never ask for a PIN. "
        "Those flags are shown with their exact words, so the user can see why.",
        "",
        "## What this doesn't show",
        "",
        "- The transcripts were written for the test, not taken from real calls, and the rules were tuned on "
        "similar phrasing, so real-world recall will be lower.",
        "- Live calls add speech-recognition errors (Hindi on phone audio especially; see README §5).",
        "- The local LLM layer, which adds flags the phrases miss, isn't part of this test.",
        "- The voice model is measured separately: `eval/voice_eval.py`, on recordings.",
        "",
    ]
    OUT.write_text("\n".join(md), encoding="utf-8")

    for name in ("alert", "signs"):
        r = at[name]
        print(f"{name:6} recall {r['recall']:.0%}  false alarms {r['false_alarm']:.0%}  precision {r['precision']:.0%}")
    print(f"missed at the alert: {[r['id'] for r in missed]}")
    print(f"ordinary calls >= {SIGNS}: {[r['id'] for r in alarms]}")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
